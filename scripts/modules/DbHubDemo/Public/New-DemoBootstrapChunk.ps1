function New-DemoBootstrapChunk {
    <#
    .SYNOPSIS
    Splits the bootstrap bundle into Run Command scripts that each write one SHA-256-checked chunk on a VM
    (ADR 0003).

    .DESCRIPTION
    Pure: it reads one file and returns objects, with no Azure calls and nothing written. Each object has
    Index, Count, Name, Sha256 (of the chunk), BundleSha256, SizeBytes, and Script. Send-DemoBootstrapBundle
    sends the scripts one at a time.

    - Name is the deterministic Run Command name DbHubDemo-Chunk-<first 12 hex digits of the bundle
      SHA-256>-<index, 3 digits>, so a VM can't confuse two bundles.
    - Script is an ASCII-only Windows PowerShell 5.1 script with the chunk's Base64 data and expected hashes
      inlined; it takes no Run Command parameters. It creates <Root>\downloads\<sha12> (restricting <Root>
      to SYSTEM and Administrators when it creates it, like the loader), decodes the data, checks its
      SHA-256 (exit 1 without writing anything on a mismatch), and writes chunk-<nnn>.bin and
      chunk-<nnn>.sha256 atomically (a temporary file, then a move). It exits 0 without writing when the
      chunk is already there with the right hash, so resending is safe.
    - Nothing secret may travel in a chunk: the file, or each entry of a zip, is checked against the
      registered secrets and the module's redaction patterns first, and the function refuses to continue
      on a match (ADR 0009).

    Learn documents no size limit for inline Run Command scripts (checked 2026-10-20). 512 KiB of raw data
    (about 700 KB of script) is the default, the largest size proven live on 2026-10-20.

    .PARAMETER Path
    The bundle zip from New-DemoBootstrapBundle.

    .PARAMETER ChunkSizeKiB
    Raw bytes per chunk, in KiB: 1 to 512. Base64 makes each script about a third larger.

    .PARAMETER Root
    State folder on the VM. Defaults to C:\ProgramData\DbHubDemo, the folder the loader reads.

    .EXAMPLE
    $chunks = New-DemoBootstrapChunk -Path (New-DemoBootstrapBundle).Path
    #>
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseShouldProcessForStateChangingFunctions', '', Justification = 'Pure: returns objects and changes no state.')]
    [CmdletBinding()]
    [OutputType([pscustomobject[]])]
    param(
        [Parameter(Mandatory)]
        [string] $Path,

        [ValidateRange(1, 512)]
        [int] $ChunkSizeKiB = 512,

        # Printable ASCII without a single quote: the path is inlined in a single-quoted string.
        [ValidatePattern('^[A-Za-z]:\\[\x20-\x26\x28-\x7E]+$')]
        [string] $Root = 'C:\ProgramData\DbHubDemo'
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "The bundle file $Path doesn't exist. Run New-DemoBootstrapBundle first."
    }
    Assert-DemoNoSecretContent -Path $Path
    $bytes = [System.IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -eq 0) {
        throw "The bundle file $Path is empty."
    }
    $bundleSha256 = [System.Convert]::ToHexString([System.Security.Cryptography.SHA256]::HashData($bytes)).ToLowerInvariant()
    $shortSha = $bundleSha256.Substring(0, 12)
    $chunkSize = $ChunkSizeKiB * 1024
    $count = [int][System.Math]::Ceiling($bytes.Length / [double]$chunkSize)
    if ($count -gt 999) {
        throw "The bundle needs $count chunks of $ChunkSizeKiB KiB; the names allow 999. Use a larger -ChunkSizeKiB."
    }

    # Single-quoted template: tokens are replaced below, and the generated script must stay ASCII.
    $template = @'
# DbHubDemo bootstrap bundle chunk __INDEX__ of __COUNT__ (ADR 0003). Generated by New-DemoBootstrapChunk.
# It holds no secrets. It writes __ROOT__\downloads\__SHA12__\__NAME__.bin and .sha256 after checking the
# chunk's SHA-256, and exits 0 without writing when the chunk is already there. Windows PowerShell 5.1.
$ErrorActionPreference = 'Stop'
$root = '__ROOT__'
$folder = Join-Path -Path $root -ChildPath 'downloads\__SHA12__'
$name = '__NAME__'
$expected = '__SHA256__'
$data = @"
__DATA__
"@

function Get-DemoChunkSha256 {
    param([byte[]] $Bytes)
    $algorithm = [System.Security.Cryptography.SHA256]::Create()
    try {
        return ([System.BitConverter]::ToString($algorithm.ComputeHash($Bytes)) -replace '-', '').ToLowerInvariant()
    }
    finally {
        $algorithm.Dispose()
    }
}

try {
    $binPath = Join-Path -Path $folder -ChildPath ($name + '.bin')
    $shaPath = Join-Path -Path $folder -ChildPath ($name + '.sha256')
    if ((Test-Path -LiteralPath $binPath -PathType Leaf) -and (Test-Path -LiteralPath $shaPath -PathType Leaf)) {
        $present = Get-DemoChunkSha256 -Bytes ([System.IO.File]::ReadAllBytes($binPath))
        if ($present -eq $expected -and ([System.IO.File]::ReadAllText($shaPath)).Trim() -eq $expected) {
            [Console]::Out.WriteLine('Chunk __INDEX__ of __COUNT__ for bundle __SHA12__ is already present.')
            exit 0
        }
    }
    $bytes = [System.Convert]::FromBase64String($data)
    $actual = Get-DemoChunkSha256 -Bytes $bytes
    if ($actual -ne $expected) {
        [Console]::Error.WriteLine(('Chunk __INDEX__ of __COUNT__: SHA-256 mismatch (expected {0}, got {1}). Nothing was written.' -f $expected, $actual))
        exit 1
    }
    if (-not (Test-Path -LiteralPath $root)) {
        New-Item -ItemType Directory -Path $root -Force | Out-Null
        $output = & icacls.exe $root /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' /C /Q 2>&1
        if ($LASTEXITCODE -ne 0) {
            throw ('icacls failed with exit code {0}: {1}' -f $LASTEXITCODE, ($output -join ' '))
        }
    }
    if (-not (Test-Path -LiteralPath $folder)) {
        New-Item -ItemType Directory -Path $folder -Force | Out-Null
    }
    $temporary = $binPath + '.tmp'
    [System.IO.File]::WriteAllBytes($temporary, $bytes)
    if (Test-Path -LiteralPath $binPath) {
        Remove-Item -LiteralPath $binPath -Force
    }
    [System.IO.File]::Move($temporary, $binPath)
    $temporary = $shaPath + '.tmp'
    [System.IO.File]::WriteAllText($temporary, $expected, [System.Text.Encoding]::ASCII)
    if (Test-Path -LiteralPath $shaPath) {
        Remove-Item -LiteralPath $shaPath -Force
    }
    [System.IO.File]::Move($temporary, $shaPath)
    [Console]::Out.WriteLine('Chunk __INDEX__ of __COUNT__ for bundle __SHA12__ written: __SIZE__ bytes.')
    exit 0
}
catch {
    [Console]::Error.WriteLine('Chunk __INDEX__ of __COUNT__ failed: ' + $_.Exception.Message)
    exit 1
}
'@

    $chunks = [System.Collections.Generic.List[object]]::new()
    for ($i = 0; $i -lt $count; $i++) {
        $offset = $i * $chunkSize
        $length = [System.Math]::Min($chunkSize, $bytes.Length - $offset)
        $chunk = [byte[]]::new($length)
        [System.Array]::Copy($bytes, $offset, $chunk, 0, $length)
        $index = $i + 1
        $chunkSha256 = [System.Convert]::ToHexString([System.Security.Cryptography.SHA256]::HashData($chunk)).ToLowerInvariant()
        $data = [System.Convert]::ToBase64String($chunk, [System.Base64FormattingOptions]::InsertLineBreaks).Replace("`r`n", "`n")
        $fileName = 'chunk-{0:d3}' -f $index
        $tokens = [ordered]@{
            '__INDEX__'  = [string]$index
            '__COUNT__'  = [string]$count
            '__ROOT__'   = $Root
            '__SHA12__'  = $shortSha
            '__NAME__'   = $fileName
            '__SHA256__' = $chunkSha256
            '__SIZE__'   = [string]$length
            '__DATA__'   = $data
        }
        $scriptText = $template.Replace("`r`n", "`n")
        foreach ($token in $tokens.Keys) {
            $scriptText = $scriptText.Replace($token, $tokens[$token])
        }
        $runCommandName = 'DbHubDemo-Chunk-{0}-{1:d3}' -f $shortSha, $index
        $chunks.Add([pscustomobject]@{
                Index        = $index
                Count        = $count
                Name         = $runCommandName
                Sha256       = $chunkSha256
                BundleSha256 = $bundleSha256
                SizeBytes    = $length
                Script       = $scriptText
            })
    }
    return $chunks.ToArray()
}
